export type TranslationNamespace = keyof typeof translations.vi;
export type TranslationKey<N extends TranslationNamespace> = keyof (typeof translations.vi)[N] & string;

export function translate<N extends TranslationNamespace>(
  locale: Locale,
  namespace: N,
  key: TranslationKey<N>,
  params?: Record<string, string | number | null | undefined>,
) {
  const safeLocale = isLocale(locale) ? locale : DEFAULT_LOCALE;
  const tree = translations[safeLocale][namespace] as Record<string, string>;
  const fallbackTree = translations[DEFAULT_LOCALE][namespace] as Record<string, string>;
  const template = tree[key] ?? fallbackTree[key] ?? key;
  return interpolate(template, params);
}

export const customerStrings = translations;

export function formatMoneyVnd(value: number | null | undefined, locale: Locale) {
  if (!Number.isFinite(Number(value ?? 0))) return locale === "en" ? "VND 0" : "0đ";
  if (locale === "en") {
    return `VND ${new Intl.NumberFormat("en-US").format(Number(value ?? 0))}`;
  }
  return `${new Intl.NumberFormat("vi-VN").format(Number(value ?? 0))}đ`;
}

export function formatDateLabel(value: string | Date | null | undefined, locale: Locale) {
  if (!value) return "";
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return date.toLocaleDateString(locale === "en" ? "en-US" : "vi-VN");
}

export function formatDateTimeLabel(value: string | Date | null | undefined, locale: Locale) {
  if (!value) return "";
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return date.toLocaleString(locale === "en" ? "en-US" : "vi-VN", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
}

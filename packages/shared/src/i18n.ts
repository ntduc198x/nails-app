export type Locale = "vi" | "en";

export const DEFAULT_LOCALE: Locale = "vi";
export const SUPPORTED_LOCALES: readonly Locale[] = ["vi", "en"] as const;

type TranslationLeaf = string;
type TranslationTree = Record<string, TranslationLeaf>;
type TranslationBundle = Record<Locale, Record<string, TranslationTree>>;

function interpolate(template: string, params?: Record<string, string | number | null | undefined>) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    const value = params[key];
    return value == null ? "" : String(value);
  });
}

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "vi" || value === "en";
}

export function normalizeLocale(value: string | null | undefined): Locale {
  if (isLocale(value)) return value;
  if (!value) return DEFAULT_LOCALE;
  const lower = value.toLowerCase();
  if (lower.startsWith("en")) return "en";
  return DEFAULT_LOCALE;
}

export function pickPreferredLocale(input: Array<string | null | undefined>): Locale {
  for (const item of input) {
    if (!item) continue;
    const normalized = normalizeLocale(item);
    if (normalized) return normalized;
  }
  return DEFAULT_LOCALE;
}

